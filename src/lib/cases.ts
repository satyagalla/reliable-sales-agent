type CaseSpec = {
  id: string;
  tenant: string;
  language: "en" | "ar";
  text: string;
  draft: Draft;
  expected: {
    decision: string;
    total?: number;
    row?: string;
    quantity?: number;
    periods?: number;
    noRows?: boolean;
  };
  tags: string[];
};
function c(
  id: string,
  tenant: string,
  language: "en" | "ar",
  text: string,
  patch: Partial<Draft>,
  expected: CaseSpec["expected"],
  tags: string[],
): CaseSpec {
  return {
    id,
    tenant,
    language,
    text,
    draft: {
      language,
      intent: "quote",
      lines: [],
      discount_pct: 0,
      city: tenant === "qamar" ? "Dubai" : "Riyadh",
      commitments: [],
      risk: "low",
      missing: [],
      reply:
        language === "ar"
          ? "سيتحقق فريقنا من المتطلبات والتوفر."
          : "Our team will verify requirements and availability.",
      evidence: [text],
      ...patch,
    },
    expected,
    tags,
  };
}
